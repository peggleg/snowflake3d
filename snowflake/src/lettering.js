export function lettering(text,radius,branch){
 const count=text.length*5-1,unit=Math.min(radius*.065,radius*.74/count,radius*.26/(3+count*.29)),start=radius*.54-count*unit/2;
 const width=Math.max(.8,branch*.55),segments=[];
 for(let i=0;i<text.length;i++)for(const stroke of glyphs[text[i]]||[]){
  for(let j=1;j<stroke.length;j++){
   const a=stroke[j-1],b=stroke[j];segments.push([[start+(i*5+a[0])*unit,(a[1]-3)*unit],[start+(i*5+b[0])*unit,(b[1]-3)*unit]]);
  }
 }
 return {segments,width,unit,printable:2*unit-width>=.6};
}
export function normalizeText(text){return String(text).normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toUpperCase().trim().replace(/\s+/g,' ');}
